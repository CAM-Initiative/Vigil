def repo_relative_path(path: Path) -> str:
    try:
        return path.resolve().relative_to(ROOT.resolve()).as_posix()
    except ValueError:
        return path.as_posix()


def github_blob_url(path: str) -> str:
    return f"https://github.com/{REPOSITORY}/blob/{DEFAULT_BRANCH}/{path}"


def raw_url(path: str) -> str:
    return f"https://raw.githubusercontent.com/{REPOSITORY}/{DEFAULT_BRANCH}/{path}"


def record_files(directories: list[Path] | None = None) -> list[Path]:
    """Return individual JSON records and Markdown research records."""
    files: list[Path] = []
    for directory in directories or RECORD_TYPE_DIRS:
        if directory.exists():
            pattern = "*.md" if directory.name == "research" else "*.json"
            files.extend(directory.rglob(pattern))
    return sorted(files, key=lambda path: path.as_posix())


def contains_key(value: Any, key: str) -> bool:
    if isinstance(value, dict):
        return key in value or any(contains_key(item, key) for item in value.values())
    if isinstance(value, list):
        return any(contains_key(item, key) for item in value)
    return False


def parse_research_front_matter(path: Path) -> dict[str, Any]:
    text = path.read_text(encoding="utf-8")
    if not text.startswith("---\n"):
        raise ValueError(f"{path} must begin with JSON front matter")
    end = text.find("\n---\n", 4)
    if end == -1:
        raise ValueError(f"{path} has unterminated JSON front matter")
    metadata = json.loads(text[4:end])
    if not isinstance(metadata, dict):
        raise TypeError(f"{path} research front matter must contain one JSON object")
    return metadata


def load_records(directories: list[Path] | None = None) -> list[dict[str, Any]]:
    records: list[dict[str, Any]] = []
    for path in record_files(directories):
        if path.suffix == ".md":
            record = parse_research_front_matter(path)
        else:
            with path.open("r", encoding="utf-8") as handle:
                record = json.load(handle)
        if not isinstance(record, dict):
            raise TypeError(f"{path} must contain one JSON object")
        if contains_key(record, "source_data"):
            raise ValueError(f"{path} contains forbidden source_data")
        record = dict(record)
        record["__source_path"] = path
        records.append(record)
    return sorted(records, key=lambda record: record.get("id", ""))


def prune_empty(value: Any) -> Any:
    """Recursively remove empty generated-output values while preserving uncertainty text."""
    if isinstance(value, dict):
        pruned = {key: prune_empty(item) for key, item in value.items() if key != "__source_path"}
        return {
            key: item
            for key, item in pruned.items()
            if key in PRESERVE_EMPTY_KEYS or item not in (None, "", [], {})
        }
    if isinstance(value, list):
        pruned_items = [prune_empty(item) for item in value]
        return [item for item in pruned_items if item not in (None, "", [], {})]
    return value


def dict_summary(record: dict[str, Any], field: str, keys: list[str] | None = None) -> dict[str, Any]:
    section = record.get(field)
    if not isinstance(section, dict):
        return {}
    if keys is None:
        return dict(section)
    return {key: section.get(key, "") for key in keys}


